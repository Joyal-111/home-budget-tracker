-- Users table
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Categories table
CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(50) NOT NULL,
    CATEGORY_TYPE VARCHAR2(10) CHECK (CATEGORY_TYPE IN ('INCOME', 'EXPENSE')),
    UNIQUE (CATEGORY_NAME, CATEGORY_TYPE)
);

-- Budget table
CREATE TABLE BUDGET (
    BUDGET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    AMOUNT NUMBER(12, 2) NOT NULL,
    PERIOD VARCHAR2(20) DEFAULT 'MONTHLY',
    FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

-- Unified Transactions table (Existing structure)
CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL,
    AMOUNT NUMBER(12, 2) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    DESCRIPTION VARCHAR2(200),
    TRANSACTION_TYPE VARCHAR2(10) CHECK (TRANSACTION_TYPE IN ('INCOME', 'EXPENSE')),
    TRANSACTION_DATE DATE DEFAULT SYSDATE,
    FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

-- New Income table
CREATE TABLE INCOME (
    INCOME_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL,
    AMOUNT NUMBER(12, 2) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    INCOME_DATE DATE DEFAULT SYSDATE,
    FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

-- New Expense table
CREATE TABLE EXPENSE (
    EXPENSE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USERNAME VARCHAR2(50) NOT NULL,
    AMOUNT NUMBER(12, 2) NOT NULL,
    CATEGORY VARCHAR2(50) NOT NULL,
    EXPENSE_DATE DATE DEFAULT SYSDATE,
    FOREIGN KEY (USERNAME) REFERENCES USERS(USERNAME)
);

